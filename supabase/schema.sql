-- ── Cuenta bancaria bi-moneda (Banco Santander) (agregado 2026-06-25) ────────
-- Libro mayor de la cuenta que Mimi usa para alquileres (señas que le pagan,
-- gastos que paga). Lleva pesos y USD a la vez. `delta_*` positivo = entra,
-- negativo = sale. Esta tabla SOLO guarda lo que no está en otras tablas:
--   apertura (saldo inicial), compra/venta de USD (fx, libre, sin dólar blue) y
--   movimientos manuales. Las señas de reservas (deposit_account='Santander') y
--   los egresos con payment_method='Santander' se suman/restan en las lecturas
--   (src/db/cuenta.ts), no se duplican acá. Soft-delete con `cancelled_at`.
-- ⚠️ Aplicar SOLO esta sentencia en Supabase — nunca el archivo entero. Ruca, public.
CREATE TABLE cuenta_movimientos (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    date         DATE NOT NULL,
    account      TEXT NOT NULL DEFAULT 'Santander',
    kind         TEXT NOT NULL CHECK (kind IN ('apertura','ingreso','egreso','fx')),
    delta_ars    NUMERIC NOT NULL DEFAULT 0,   -- + entra, - sale
    delta_usd    NUMERIC NOT NULL DEFAULT 0,
    description  TEXT,
    notes        TEXT,
    cancelled_at TIMESTAMPTZ,                  -- soft-delete (nunca DELETE)
    created_at   TIMESTAMPTZ NOT NULL DEFAULT now()
);

